// Local operator only: no web endpoint, embedded secrets, inferred prices or spending.
import {createInterface} from 'node:readline/promises';
import {execFileSync} from 'node:child_process';
import {writeFileSync,mkdirSync} from 'node:fs';
import {randomUUID} from 'node:crypto';
import {resolve} from 'node:path';
import {fileURLToPath} from 'node:url';
import {configurationManifest} from '../../scripts/configure-providers.mjs';
export function dollars(value){
 if(!/^(0|[1-9]\d{0,3})(\.\d{1,6})?$/.test(value))throw Error('Enter a positive USD amount with at most six decimal places.');
 const [whole,fraction='']=value.split('.');const micros=Number(whole)*1000000+Number(fraction.padEnd(6,'0'));
 if(micros<=0)throw Error('Amount must be positive.');return micros;
}
export async function setupWizard(io){
 const action=await io.ask('Choose: 1 = activate saved Railway settings, 2 = configure business allowance, Enter = exit: ');
 if(action==='')return {status:'cancelled'};
 if(action==='1'){
  const preview=await io.run('activate-dev.mjs',[]);io.show(preview);
  if(await io.ask('Apply this exact worker/API configuration? Type ACTIVATE: ')!=='ACTIVATE')return {status:'cancelled'};
  if(!/^[a-f0-9]{64}$/.test(preview.preview_sha256??''))throw Error('Invalid activation preview.');
  const result=await io.run('activate-dev.mjs',['--apply',preview.preview_sha256]);io.show(result);return result;
 }
 if(action!=='2')throw Error('Unknown action.');
 const listed=await io.run('configure-providers.mjs',['--list']);
 if(!listed.businesses?.length){io.show('Create your business in Desvio first. No allowance changed.');return {status:'no_business'};}
 listed.businesses.forEach((b,i)=>io.show(`${i+1}. ${b.name} (${b.business_id})`));
 const selected=await io.ask('Business number: ');
 if(!/^[1-9]\d*$/.test(selected)||Number(selected)>listed.businesses.length)throw Error('Choose a listed business.');
 const b=listed.businesses[Number(selected)-1];
 const kind=await io.ask('Capability: onboarding, creative, gemini_creative, planning, insights or video: ');
 if(!['onboarding','creative','gemini_creative','planning','insights','video'].includes(kind))throw Error('Unknown capability.');
 const g={kind,enabled:true};
 io.show('This authorizes paid requests by this business. No request is generated by setup. Each capability has its own lifetime cap, including earlier usage. Use verified provider prices and eligible model IDs.');
 const days=await io.ask('Allowance validity in whole days (1–30): ');
 if(!/^(?:[1-9]|[12]\d|30)$/.test(days))throw Error('Validity must be 1–30 days.');
 g.expires_at=new Date(io.now()+Number(days)*86400000).toISOString();
 g.budget_micros=dollars(await io.ask('Lifetime cap for this capability (USD): '));
 if(['planning','insights'].includes(kind))g.provider=await io.ask('Provider (openai or gemini): ');
 if(kind==='video'){
  const choice=await io.ask('Video: 1 = create, 2 = edit, 3 = both: ');
  if(!['1','2','3'].includes(choice))throw Error('Choose 1, 2 or 3.');
  g.models=choice==='1'?['kling-video/v3.0/std/image-to-video']:choice==='2'?['kling-video/o3/video-edit']:['kling-video/v3.0/std/image-to-video','kling-video/o3/video-edit'];
  g.max_create_micros=dollars(await io.ask('Maximum reserved cost per video create request (USD): '));
  g.max_edit_micros=dollars(await io.ask('Maximum reserved cost per video edit request (USD): '));
 }else{
  g[['creative','gemini_creative'].includes(kind)?'text_model':'model']=await io.ask('Exact eligible text model ID: ');
  // USD per million tokens is numerically equal to micros per token.
  for(const [field,label] of [['input_micros_per_token','Input'],['output_micros_per_token','Output']]){
   const value=await io.ask(`${label} token price (USD per million tokens): `);
   if(!/^(0|[1-9]\d*)(\.\d{1,6})?$/.test(value))throw Error('Enter a verified positive decimal token price.');g[field]=Number(value);
  }
  if(kind==='creative'){
   g.image_model=await io.ask('Exact eligible image model ID: ');g.quality=await io.ask('Image quality (low, medium or high): ');
   g.max_image_request_micros=dollars(await io.ask('Maximum reserved cost per image request (USD): '));
  }
 }
 const manifest=configurationManifest({version:1,change_id:io.id(),organization_id:b.organization_id,business_id:b.business_id,operator_reference:'Local guided setup: '+await io.ask('Reason/reference for this spending authorization: '),grants:[g]},io.now());
 const file=await io.save(manifest);const preview=await io.run('configure-providers.mjs',[file]);io.show(preview);
 io.show('Saved manifest: '+file+'. Keep this file/change ID to reconcile an interrupted apply; do not create a new allowance blindly.');
 if(await io.ask('Authorize the displayed allowance? Type AUTHORIZE: ')!=='AUTHORIZE')return {status:'cancelled',file};
 if(!/^[a-f0-9]{64}$/.test(preview.preview_sha256??''))throw Error('Invalid allowance preview.');
 const result=await io.run('configure-providers.mjs',[file,'--apply',preview.preview_sha256]);io.show(result);return result;
}
if(process.argv[1]&&resolve(process.argv[1])===fileURLToPath(import.meta.url)){
 if(!process.stdin.isTTY||!process.stdout.isTTY){console.error('Run this guided setup in an interactive local terminal.');process.exitCode=1;}
 else{
  const prompt=createInterface({input:process.stdin,output:process.stdout});
  try{await setupWizard({ask:q=>prompt.question(q),show:v=>console.log(typeof v==='string'?v:JSON.stringify(v,null,2)),now:Date.now,id:randomUUID,
   save:async manifest=>{mkdirSync('work',{recursive:true});const file=resolve('work/provider-allowance-'+manifest.change_id+'.json');writeFileSync(file,JSON.stringify(manifest,null,2)+'\n',{mode:0o600,flag:'wx'});return file;},
   run:async(script,args)=>{try{return JSON.parse(execFileSync(process.execPath,[new URL(script,import.meta.url).pathname,...args],{encoding:'utf8',timeout:900000,stdio:['ignore','pipe','pipe']}));}catch(e){const code=e.stderr?.toString().match(/(?:ACTIVATION|CONFIGURATION|PROVIDER_SETUP)_[A-Z_]+/g)?.at(-1);throw Error(code??'Setup did not confirm completion. Reconcile the saved change before retrying.');}}
  });}catch(e){console.error(e.message);process.exitCode=1;}finally{prompt.close();}
 }
}
