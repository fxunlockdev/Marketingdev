#!/usr/bin/env python3
"""Fail-closed *structural* checker for Codex-generated integration evidence.

This is NOT a substitute for real staging tests or an attested test runner. No file
can prove a provider request occurred merely by declaring LIVE_VERIFIED. Codex must
implement actual live smoke tests that independently generate this evidence.

Usage: python scripts/check_release_evidence.py PATH/TO/integration-status.json
"""
import json
import re
import sys
from pathlib import Path


def verify(path: Path) -> list[str]:
    errors=[]
    try:
        data=json.loads(path.read_text(encoding='utf-8'))
    except Exception as exc:
        return [f'Cannot read JSON: {exc}']
    if data.get('environment') != 'production':
        errors.append('Gate requires a production evidence manifest')
    if data.get('overall_release_state') != 'LAUNCH_READY':
        errors.append('Overall release state must be LAUNCH_READY')
    if data.get('generated_by') in (None, '', 'manual'):
        errors.append('Evidence must be generated by a named automated runner')
    if not re.fullmatch(r'[a-f0-9]{7,40}',str(data.get('code_commit',''))):
        errors.append('Use an actual Git commit SHA')
    security=data.get('security') or {}
    for key in ('tenant_isolation_passed','secret_scan_passed'):
        if security.get(key) is not True:
            errors.append(f'Security check missing or false: {key}')
    integrations=data.get('integrations')
    if not isinstance(integrations,dict) or not integrations:
        errors.append('Integration evidence missing')
    else:
        for name, row in integrations.items():
            if row.get('state') != 'LAUNCH_READY':
                errors.append(f'{name} not LAUNCH_READY: {row.get("state")}')
            if row.get('live_test') is not True:
                errors.append(f'{name} has no verified live test')
            if not row.get('evidence'):
                errors.append(f'{name} has no evidence references')
            if row.get('blocked_reason'):
                errors.append(f'{name} still blocked: {row["blocked_reason"]}')
    return errors


def main():
    if len(sys.argv)!=2:
        print('Usage: python check_release_evidence.py path/to/integration-status.json',file=sys.stderr)
        return 2
    failures=verify(Path(sys.argv[1]))
    if failures:
        print('RELEASE BLOCKED:')
        for f in failures: print(f'  - {f}')
        return 1
    print('Structural gate passed. Still require independently executed live tests and security signoff.')
    return 0

if __name__=='__main__': sys.exit(main())
