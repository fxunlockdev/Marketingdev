#!/usr/bin/env node
/**
 * UI token guardrail for apps/web.
 *
 * Fails when a file gains, compared with scripts/ui-token-baseline.json:
 *   - hex colour literals outside apps/web/app/tokens.css (CSS, TS and TSX);
 *   - `!important`;
 *   - `outline: none` / `outline: 0` (focus must stay visible).
 *
 * The baseline records today's debt per file, so existing code passes and the
 * numbers can only go down. A file that is not in the baseline must be clean.
 *
 *   node scripts/check-ui-tokens.mjs            check; exit 1 on any increase
 *   node scripts/check-ui-tokens.mjs --update   rewrite the baseline after
 *                                               removing debt (refuses to
 *                                               record an increase)
 *
 * To add a colour: define it in apps/web/app/tokens.css and reference the token.
 */
import {readdirSync, readFileSync, writeFileSync, statSync} from 'node:fs';
import {dirname, join, relative, sep} from 'node:path';
import {fileURLToPath} from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const webRoot = join(root, 'apps', 'web');
const baselinePath = join(root, 'scripts', 'ui-token-baseline.json');
const tokenFile = 'apps/web/app/tokens.css';
const skippedDirectories = new Set(['node_modules', '.next', 'public']);
const metrics = ['hex', 'important', 'outlineNone'];
const labels = {hex: 'hex colour literals', important: '!important', outlineNone: 'outline: none'};

/** @returns {string[]} repo-relative paths, POSIX separators, sorted */
function sourceFiles(directory) {
  return readdirSync(directory).flatMap(name => {
    const path = join(directory, name);
    if (statSync(path).isDirectory()) return skippedDirectories.has(name) ? [] : sourceFiles(path);
    return /\.(css|tsx?)$/.test(name) && !name.endsWith('.d.ts') ? [relative(root, path).split(sep).join('/')] : [];
  }).sort();
}

const stripComments = text => text.replace(/\/\*[\s\S]*?\*\//g, '');
const count = (text, pattern) => (text.match(pattern) ?? []).length;

/** Hex colours in CSS declaration values only, so `#main` in a selector is not counted. */
function cssHex(text) {
  return (text.match(/:[^;{}]*/g) ?? []).reduce((total, value) => total + count(value, /#(?:[0-9a-f]{8}|[0-9a-f]{6}|[0-9a-f]{3,4})\b/gi), 0);
}

/** Hex colours in quoted strings, which is how inline styles and defaults carry them. */
function scriptHex(text) {
  return count(text, /(['"`])#(?:[0-9a-f]{8}|[0-9a-f]{6}|[0-9a-f]{3,4})\1/gi);
}

/** @returns {{hex: number, important: number, outlineNone: number}} */
function measure(file) {
  const raw = readFileSync(join(root, file), 'utf8');
  if (!file.endsWith('.css')) return {hex: scriptHex(raw), important: 0, outlineNone: 0};
  const text = stripComments(raw);
  return {
    hex: file === tokenFile ? 0 : cssHex(text),
    important: count(text, /!\s*important/gi),
    outlineNone: count(text, /outline\s*:\s*(?:none|0)\s*(?:!\s*important\s*)?[;}]/gi),
  };
}

const current = Object.fromEntries(sourceFiles(webRoot).map(file => [file, measure(file)])
  .filter(([, counts]) => metrics.some(metric => counts[metric] > 0)));
const totals = counts => Object.fromEntries(metrics.map(metric => [metric, Object.values(counts).reduce((sum, file) => sum + file[metric], 0)]));

let baseline;
try {
  baseline = JSON.parse(readFileSync(baselinePath, 'utf8')).files;
} catch (error) {
  if (error.code !== 'ENOENT') throw error;
  baseline = null;
}

const increases = baseline === null ? [] : Object.entries(current).flatMap(([file, counts]) => metrics
  .filter(metric => counts[metric] > (baseline[file]?.[metric] ?? 0))
  .map(metric => `${file}: ${labels[metric]} ${baseline[file]?.[metric] ?? 0} → ${counts[metric]}`));

if (increases.length) {
  process.stderr.write(`UI token guardrail failed. New debt:\n  ${increases.join('\n  ')}\n\n` +
    `Use a token from ${tokenFile} instead of a hex literal, raise specificity instead of !important,\n` +
    'and style :focus-visible instead of removing the outline.\n');
  process.exit(1);
}

if (process.argv.includes('--update') || baseline === null) {
  writeFileSync(baselinePath, JSON.stringify({
    note: 'Generated by scripts/check-ui-tokens.mjs --update. Counts may only decrease.',
    totals: totals(current),
    files: current,
  }, null, 2) + '\n');
  process.stdout.write(`UI token baseline written: ${JSON.stringify(totals(current))}\n`);
} else {
  const before = totals(baseline), now = totals(current);
  const reduced = metrics.filter(metric => now[metric] < before[metric]);
  process.stdout.write(`UI token guardrail passed: ${JSON.stringify(now)}\n` +
    (reduced.length ? `Debt went down (${reduced.map(metric => `${labels[metric]} ${before[metric]} → ${now[metric]}`).join(', ')}). Run with --update to lock it in.\n` : ''));
}
